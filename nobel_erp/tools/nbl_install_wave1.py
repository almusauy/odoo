NAMES = ['hr_payroll', 'hr_payroll_account', 'crm']

Mod = env['ir.module.module'].sudo()

# ① ما موجود بالمسار أصلاً ⇒ نوقف بلا ما نلمس شي
present = Mod.search_read([('name', 'in', NAMES)], ['name', 'state'])
found = []
for r in present:
    found.append(r['name'])
missing = []
for n in NAMES:
    if n not in found:
        missing.append(n)
if missing:
    raise UserError(
        "⛔ ما لكيت هذي الموديولات بالمسار: %s\n\n"
        "سوّي «تحديث قائمة التطبيقات» من شاشة التطبيقات ثم أعد التشغيل."
        % ", ".join(missing))

# ② المنصَّب أصلاً نتركه — ⛔ ولا نعيد تنصيب شي
todo = Mod.search([('name', 'in', NAMES), ('state', '=', 'uninstalled')])
if not todo:
    raise UserError(
        "✅ الثلاثة منصَّبة أصلاً — ماكو شي ينعمل.\n\n"
        "الحالات: %s" % ", ".join(
            ["%s=%s" % (r['name'], r['state']) for r in present]))

# ③ التنصيب
action = todo.button_immediate_install()
