def esc(t):
    return t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')

def p(t): return '<p>%s</p>' % t
def h2(t, anchor=None): return '<h2 id="%s">%s</h2>' % (anchor or '', t)
def h3(t): return '<h3>%s</h3>' % t
def h4(t): return '<h4>%s</h4>' % t
def ul(items): return '<ul>' + ''.join('<li>%s</li>' % i for i in items) + '</ul>'
def ol(items): return '<ol>' + ''.join('<li>%s</li>' % i for i in items) + '</ol>'
def note(t, kind='info'): return '<div class="note %s">%s</div>' % (kind, t)
def steps(items):
    return '<ol class="steps">' + ''.join('<li>%s</li>' % i for i in items) + '</ol>'
def table(head, rows):
    return ('<table><thead><tr>' + ''.join('<th>%s</th>' % h for h in head) + '</tr></thead><tbody>'
            + ''.join('<tr>' + ''.join('<td>%s</td>' % c for c in r) + '</tr>' for r in rows)
            + '</tbody></table>')
def chapter(num, title, anchor, body):
    return '<section class="chapter" id="%s"><div class="chnum">الفصل %s</div><h1>%s</h1>%s</section>' % (anchor, num, title, body)

